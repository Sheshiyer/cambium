import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const relative = 'docs/assets/visual-flow/system-atlas';
const library = 'docs/assets/visual-flow/organ-console';
const out = resolve(root, relative);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const ids = ['genesis','taste','hands','will','cortex','vestibule','adytum','nutrix','auspex','circulator','praeceptor'];
const map = JSON.parse(await readFile(resolve(root, library, 'ASSET-MAP.v1.json'), 'utf8'));
const checking = process.argv.includes('--check');
if (!checking && !process.argv.includes('--write')) throw new Error('Use --write or --check');
if (!checking) await mkdir(out, { recursive: true });
const prior = checking ? JSON.parse(await readFile(resolve(out, 'PORTRAITS.v1.json'), 'utf8')) : null;
const records = [];
let originalBytes = 0;
const portraits = {};
for (const id of ids) {
  const sourceId = `TSOC-ORG-${id.toUpperCase()}-CONCEPT-V1`;
  const matches = map.assets.filter(row => row.canonicalAssetId === sourceId);
  if (matches.length !== 1) throw new Error(`Ambiguous portrait ${id}`);
  const source = matches[0];
  if (source.owner !== id || source.sourceStatus !== 'selected' || source.reviewStatus !== 'selected-for-derivation') {
    throw new Error(`Unreviewed portrait ${id}`);
  }
  const input = resolve(root, library, source.relativePath);
  const original = await readFile(input);
  originalBytes += original.length;
  if (hash(original) !== source.sha256) throw new Error(`Changed source ${sourceId}`);
  const name = `${id}-concept-256.webp`;
  const output = resolve(out, name);
  const [width, height] = source.dimensions.split('x').map(Number);
  if (!width || !height) throw new Error(`Invalid source dimensions ${id}`);
  if (!checking) execFileSync('cwebp', ['-quiet','-q','72','-m','6','-resize',
    width >= height ? '256' : '0', width >= height ? '0' : '256', input,'-o',output], { timeout: 20000 });
  const bytes = await readFile(output);
  if (bytes.length > 20000) throw new Error(`Portrait exceeds20KB: ${id}`);
  const record = { organ: id, canonicalAssetId: sourceId, sourcePath: `${library}/${source.relativePath}`,
    sourceSha256: source.sha256, sourceStatus: source.sourceStatus, reviewStatus: source.reviewStatus,
    authority: 'reference-only', derivativePath: `${relative}/${name}`, format: 'image/webp',
    maxWidth: 256, maxHeight: 256, bytes: bytes.length, sha256: hash(bytes) };
  if (checking && JSON.stringify(prior.portraits.find(row => row.organ === id)) !== JSON.stringify(record)) {
    throw new Error(`Derivative lineage drift: ${id}`);
  }
  records.push(record);
  portraits[id] = `data:image/webp;base64,${bytes.toString('base64')}`;
}
const total = records.reduce((n, row) => n + row.bytes, 0);
if (total > 160000) throw new Error('Atlas portrait bundle exceeds160KB');
const manifest = { schema: 'cambium.system-atlas-portraits.v1', authority: 'reference-only',
  transformation: 'fit256px; cwebp quality72 method6; no crop; source unchanged',
  bytes: total, portraits: records };
const module = '// Generated by scripts/build-system-atlas-portraits.mjs; reference images, never runtime proof.\n'
  + 'export const SYSTEM_ATLAS_PORTRAITS: Readonly<Record<string, string>> = '
  + JSON.stringify(portraits) + ';\n';
const modulePath = resolve(root, 'shared/cambium-system-atlas-portraits.ts');
if (checking) {
  if (await readFile(modulePath, 'utf8') !== module) throw new Error('Bundled portraits drift');
} else {
  await writeFile(resolve(out, 'PORTRAITS.v1.json'), JSON.stringify(manifest, null, 2) + '\n');
  await writeFile(modulePath, module);
}
console.log(JSON.stringify({ mode: checking ? 'check' : 'write', portraits: records.length,
  originalBytes, derivativeBytes: total, bundledSourceBytes: Buffer.byteLength(module) }));
