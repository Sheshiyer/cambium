import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { tmpdir } from 'node:os';

const root = fileURLToPath(new URL('../', import.meta.url));
const library = 'docs/assets/visual-flow/source-library';
const output = 'docs/assets/visual-flow/gate-chamber';
const modulePath = resolve(root, 'apps/cambium-r3f/src/curious-world/chamber-assets.ts');
const checking = process.argv[2] === '--check';
if (process.argv.length !== 3 || !['--write', '--check'].includes(process.argv[2])) throw new Error('Use --write or --check');
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const sources = JSON.parse(await readFile(resolve(root, library, 'SOURCE-ASSET-MAP.v1.json'), 'utf8'));
const specimens = [
  { key: 'controlDial', id: 'CVF-SRC-1089', owner: 'component:control-dial', size: 384, file: 'control-dial-384.webp' },
  { key: 'signalPacket', id: 'CVF-SRC-1096', owner: 'component:signal-packet', size: 128, file: 'signal-packet-128.webp' },
];
const temporary = checking ? null : await mkdtemp(join(tmpdir(), 'cambium-gate-art-'));
const records = [], images = {}, derivatives = [];
try {
  for (const spec of specimens) {
    const matches = sources.assets.filter(row => row.sourceId === spec.id);
    const source = matches[0];
    if (matches.length !== 1 || source.semanticOwner !== spec.owner || source.authority !== 'reference-only'
      || source.duplicateOf || source.dimensions.width !== 1024 || source.dimensions.height !== 1024) throw new Error('Unreviewed component lineage');
    const sourcePath = `${library}/${source.organizedPath}`;
    const original = await readFile(resolve(root, sourcePath));
    if (hash(original) !== source.sha256) throw new Error(`Source changed: ${spec.id}`);
    const target = checking ? resolve(root, output, spec.file) : join(temporary, spec.file);
    if (!checking) execFileSync('cwebp', ['-quiet', '-q', '76', '-m', '6', '-resize', String(spec.size), String(spec.size), resolve(root, sourcePath), '-o', target], { timeout: 20000 });
    const bytes = await readFile(target);
    if (bytes.length > 40000 || bytes.toString('ascii', 8, 12) !== 'WEBP') throw new Error('Invalid or oversized chamber derivative');
    images[spec.key] = `data:image/webp;base64,${bytes.toString('base64')}`;
    records.push({ key: spec.key, sourceId: spec.id, semanticOwner: spec.owner, sourcePath, sourceSha256: source.sha256,
      derivativePath: `${output}/${spec.file}`, sha256: hash(bytes), bytes: bytes.length, dimensions: `${spec.size}x${spec.size}`, authority: 'reference-only' });
    derivatives.push({ file: spec.file, bytes });
  }
  const total = records.reduce((sum, row) => sum + row.bytes, 0);
  if (total > 50000) throw new Error('Chamber artwork exceeds50KB');
  const manifest = JSON.stringify({ schema: 'cambium.gate-chamber-art.v1', authority: 'reference-only',
    transformation: 'fit square source; cwebp quality76 method6; no crop; source unchanged', bytes: total, specimens: records }, null, 2) + '\n';
  const module = '// Generated by scripts/build-gate-chamber-assets.mjs; source specimens, never runtime proof.\n'
    + 'export const GATE_CHAMBER_ASSETS = Object.freeze(' + JSON.stringify(images) + ');\n';
  if (checking) {
    if (await readFile(resolve(root, output, 'ASSETS.v1.json'), 'utf8') !== manifest || await readFile(modulePath, 'utf8') !== module) throw new Error('Chamber artwork lineage or bundle drift');
  } else {
    await mkdir(resolve(root, output), { recursive: true });
    for (const item of derivatives) await writeFile(resolve(root, output, item.file), item.bytes);
    await writeFile(resolve(root, output, 'ASSETS.v1.json'), manifest);
    await writeFile(modulePath, module);
  }
  console.log(JSON.stringify({ mode: checking ? 'check' : 'write', specimens: records.length, derivativeBytes: total, bundledSourceBytes: Buffer.byteLength(module) }));
} finally { if (temporary) await rm(temporary, { recursive: true, force: true }); }
