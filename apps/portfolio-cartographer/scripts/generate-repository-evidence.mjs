import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(root, 'src')
const relocationDir = path.resolve(root, '../../docs/project-management/relocation-registry/thoughtseed')
const output = path.join(srcDir, 'repository-evidence.generated.ts')

const catalogModule = await import(pathToFileURL(path.join(srcDir, 'portfolio-catalog-data.ts')).href)
const evidenceModule = await import(pathToFileURL(path.join(srcDir, 'repository-evidence.ts')).href)
const inventoryModule = await import(pathToFileURL(path.join(srcDir, 'repository-inventory.generated.ts')).href)

const {
  RAW_PROGRAMS,
  RAW_SAPLINGS,
} = catalogModule
const { REPOSITORY_INVENTORY } = inventoryModule
const {
  REPOSITORY_EVIDENCE_SCHEMA,
  repositoryEvidenceDigest,
  resolveRepositoryEvidence,
} = evidenceModule

async function relocationEntries() {
  const directoryEntries = await readdir(relocationDir, { withFileTypes: true })
  const folders = directoryEntries.filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()
  const rows = []
  for (const folder of folders) {
    const entryPath = path.join(relocationDir, folder, 'entry.json')
    const entry = JSON.parse(await readFile(entryPath, 'utf8'))
    rows.push({
      stableId: String(entry.stableId ?? ''),
      githubIdentity: String(entry.githubIdentity ?? ''),
    })
  }
  return rows
}

function collectRepositorySourceRefs() {
  const sourceRefs = new Set()
  for (const row of RAW_SAPLINGS) {
    const provenance = row[5]
    for (const source of provenance) {
      if (typeof source === 'string' && source.startsWith('repo:')) sourceRefs.add(source)
    }
  }
  for (const row of RAW_PROGRAMS) {
    const provenance = row[6]
    for (const source of provenance) {
      if (typeof source === 'string' && source.startsWith('repo:')) sourceRefs.add(source)
    }
  }
  return [...sourceRefs].sort((left, right) => left.localeCompare(right, 'en', { sensitivity: 'base' }))
}

const sourceRefs = collectRepositorySourceRefs()
const entries = await relocationEntries()
const records = resolveRepositoryEvidence(sourceRefs, entries, REPOSITORY_INVENTORY)
const digest = repositoryEvidenceDigest(records)

const generated = [
  '// Generated by apps/portfolio-cartographer/scripts/generate-repository-evidence.mjs. Do not edit.',
  `export const REPOSITORY_EVIDENCE_SCHEMA = ${JSON.stringify(REPOSITORY_EVIDENCE_SCHEMA)} as const;`,
  `export const REPOSITORY_EVIDENCE_DIGEST = ${JSON.stringify(digest)} as const;`,
  `export const REPOSITORY_EVIDENCE = ${JSON.stringify(records, null, 2)} as const;`,
  '',
].join('\n')

await writeFile(output, generated, 'utf8')
console.log(`repository evidence ok · ${records.length} refs · sha256 ${digest}`)
