import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dist = path.join(root, 'dist')
const input = path.join(dist, 'index.html')
const output = path.join(root, 'bundle.html')
const workerEmbed = path.resolve(root, '../../workers/quests/src/portfolio-workbench.generated.ts')
const documentCsp = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data: blob:; connect-src 'none'; base-uri 'none'; form-action 'none'"

let html = await readFile(input, 'utf8')

html = html.replace(
  '<head>',
  `<head>\n    <meta http-equiv="Content-Security-Policy" content="${documentCsp}" />`,
)

const stylesheetPattern = /<link rel="stylesheet" crossorigin href="([^"]+)">/g
for (const match of [...html.matchAll(stylesheetPattern)]) {
  const asset = path.join(dist, match[1].replace(/^\.?\//, ''))
  const css = await readFile(asset, 'utf8')
  html = html.replace(
    match[0],
    () => `<style data-bundled="portfolio-cartographer">${css}</style>`,
  )
}

const scriptPattern = /<script type="module" crossorigin src="([^"]+)"><\/script>/g
for (const match of [...html.matchAll(scriptPattern)]) {
  const asset = path.join(dist, match[1].replace(/^\.?\//, ''))
  const script = await readFile(asset, 'utf8')
  html = html.replace(
    match[0],
    () => `<script type="module" data-bundled="portfolio-cartographer">${script}</script>`,
  )
}

html = html.replace(
  '</head>',
  '    <meta name="thoughtseed-artifact" content="portfolio-workbench@v2; offline; proposal-only" />\n  </head>',
)

if (/<script[^>]+src=|<link[^>]+rel="stylesheet"/i.test(html)) {
  throw new Error('bundle still contains external script or stylesheet references')
}
if (!html.includes('thoughtseed.portfolio-workbench.v2')) {
  throw new Error('bundle is missing the workbench contract marker')
}
if (!html.includes(`http-equiv="Content-Security-Policy" content="${documentCsp}"`)) {
  throw new Error('bundle is missing its document-enforced Content Security Policy')
}

const digest = createHash('sha256').update(html, 'utf8').digest('hex')
const literal = JSON.stringify(html).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
const generated = [
  '// Generated by apps/portfolio-cartographer/scripts/bundle.mjs. Do not edit.',
  `export const PORTFOLIO_WORKBENCH_SHA256 = ${JSON.stringify(digest)} as const;`,
  `export const PORTFOLIO_WORKBENCH_HTML = ${literal} as const;`,
  '',
].join('\n')

await Promise.all([
  writeFile(output, html, 'utf8'),
  writeFile(workerEmbed, generated, 'utf8'),
])
console.log(`bundle ok · ${Buffer.byteLength(html)} bytes · sha256 ${digest} · ${output}`)
console.log(`worker embed ok · ${workerEmbed}`)
