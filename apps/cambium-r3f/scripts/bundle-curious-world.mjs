import { build } from 'vite';
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdtemp, rm, lstat, realpath, chmod } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('Curious bundle accepts only --check');
}
const check = args[0] === '--check';
const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(app, '../../workers/quests/src/page/components/curious-world.generated.ts');
const temporary = await mkdtemp(join(tmpdir(), 'curious-pocket-build-'));
await chmod(temporary, 0o700);
const owned = await lstat(temporary);
const canonical = await realpath(temporary);
const deadline = setTimeout(() => {
  console.error('Curious bundle build exceeded its 120-second deadline; temporary evidence retained');
  process.exit(1);
}, 120_000);
deadline.unref();

async function boundedRead(path, limit, label) {
  const stat = await lstat(path);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > limit) {
    throw new Error(`Curious bundle ${label} is missing, changed or oversized`);
  }
  return await readFile(path, 'utf8');
}

try {
  const result = await build({
    configFile: join(app, 'vite.curious.config.ts'),
    logLevel: 'warn',
    build: { outDir: temporary, emptyOutDir: true, write: true },
  });
  const outputs = (Array.isArray(result) ? result : [result]).flatMap(item => item.output ?? []);
  const chunks = outputs.filter(item => item.type === 'chunk');
  if (chunks.length !== 1 || chunks[0].fileName !== 'curious-world.js' ||
      chunks[0].imports.length || chunks[0].dynamicImports.length) {
    throw new Error('Curious bundle must be one self-contained browser chunk');
  }
  const jsSource = await boundedRead(join(temporary, 'curious-world.js'), 2_000_000, 'JavaScript');
  const cssSource = await boundedRead(join(app, 'src/curious-world/styles.css'), 100_000, 'CSS');
  const license = await boundedRead(join(app, 'node_modules/three/LICENSE'), 16_384, 'Three license');
  if (license.includes('*/') || !license.includes('MIT License')) {
    throw new Error('Curious bundle requires the complete installed Three MIT notice');
  }
  const safeJs = (`/*! Three.js — MIT license\n${license}\n*/\n${jsSource}`)
    .replace(/<\/script/gi, '<\\/script').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  const safeCss = cssSource.replace(/<\/style/gi, '<\\/style');
  const digest = createHash('sha256').update(safeJs).update('\0').update(safeCss).digest('hex');
  const bytes = { js: Buffer.byteLength(safeJs), css: Buffer.byteLength(safeCss), total: Buffer.byteLength(safeJs) + Buffer.byteLength(safeCss) };
  const literal = value => JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
  const generated = [
    '// Generated by apps/cambium-r3f/scripts/bundle-curious-world.mjs. Do not edit.',
    '// Digest: SHA-256 of safe JavaScript, one NUL byte, then safe CSS.',
    `export const CURIOUS_WORLD_SHA256 = ${literal(digest)} as const;`,
    `export const CURIOUS_WORLD_BYTES = ${literal(bytes)} as const;`,
    `export const CURIOUS_WORLD_JS = ${literal(safeJs)} as const;`,
    `export const CURIOUS_WORLD_CSS = ${literal(safeCss)} as const;`,
    '',
  ].join('\n');
  if (check) {
    const existing = await boundedRead(output, 4_000_000, 'committed module');
    if (existing !== generated) throw new Error('Curious browser bundle differs from current source; run curious:bundle');
  } else {
    await writeFile(output, generated, 'utf8');
  }
  console.log(`Curious bundle ${check ? 'parity verified' : 'generated'} · ${bytes.total} bytes · sha256 ${digest}`);
} finally {
  clearTimeout(deadline);
  const current = await lstat(temporary);
  if (!current.isDirectory() || current.isSymbolicLink() || current.dev !== owned.dev ||
      current.ino !== owned.ino || await realpath(temporary) !== canonical) {
    throw new Error('Curious temporary build ownership changed; evidence retained');
  }
  await rm(temporary, { recursive: true });
}
